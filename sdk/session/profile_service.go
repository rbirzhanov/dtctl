// serviceCommands is the allowlist behind the "service" preset: one command
// path per line, sorted, so widening the surface is a one-line, reviewable diff.
//
// Only leaf paths are listed. An entry covers its own path and everything below
// it (see Profile.Allows), so listing a parent such as "exec" would admit every
// current and future "exec ..." command. Parents stay reachable without being
// listed, because a command that is an ancestor of an allowed entry is allowed.
//
// cmd/profile_service_test.go compares the surface this list resolves to,
// against dtctl's real command tree, with the service's own decision in
// cmd/testdata/service_surface.txt. A dtctl upgrade that brings a new command
// leaves it blocked and fails that test until someone decides; renaming or
// removing a listed command fails it too.
//
// Adding a command is a security decision for the service: add its path here
// and to the testdata file in the same change.
//
// A bare group with no allowed command beneath it ("update azure", "update gcp"
// in the embedding service's own list) is left out too: it offers nothing to run, and listing
// it would admit all its subcommands under prefix matching.
//
